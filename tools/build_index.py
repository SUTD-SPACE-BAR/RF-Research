#!/usr/bin/env python3
"""Regenerate INDEX.md and FAQ.md from tools/taxonomy.md + kb/ page front-matter.

Usage:
    python3 tools/build_index.py            # rebuild INDEX.md and FAQ.md
    python3 tools/build_index.py --check    # also report broken relative links and pages
                                            # missing required template sections
Front-matter keys used: title, domain, slug, level, confidence.
FAQ entries come from the bullets under "## Questions this page answers".
"""
import os, re, sys, glob
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KB = os.path.join(ROOT, "kb")
REQUIRED = ["Questions this page answers", "TL;DR", "Intuition", "The math",
            "Worked example", "Common mistakes", "Sources"]


def parse_taxonomy():
    txt = open(os.path.join(ROOT, "tools", "taxonomy.md")).read()
    domains, cur = [], None
    for line in txt.splitlines():
        m = re.match(r"^## (\d\d-[a-z0-9-]+)\s*(?:—\s*(.*))?$", line.strip())
        if m:
            cur = {"id": m.group(1), "desc": (m.group(2) or "").strip(), "slugs": []}
            domains.append(cur)
            continue
        if cur and line.strip() and not line.startswith("#"):
            cur["slugs"] += [s.strip() for s in line.split("·") if s.strip()]
    return domains


def parse_page(path):
    txt = open(path, encoding="utf-8").read()
    fm = {}
    m = re.match(r"^---\n(.*?)\n---\n", txt, re.S)
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                fm[k.strip()] = v.split("#")[0].strip()
    title = fm.get("title") or (re.search(r"^# (.+)$", txt, re.M) or [None, os.path.basename(path)])[1]
    qs = []
    qm = re.search(r"^## Questions this page answers\s*\n(.*?)(?=^## )", txt, re.S | re.M)
    if qm:
        for line in qm.group(1).splitlines():
            line = line.strip()
            if line.startswith(("- ", "* ")):
                qs.append(line[2:].strip())
    heads = re.findall(r"^##+ (.+)$", txt, re.M)
    return {"path": path, "title": title, "fm": fm, "questions": qs, "text": txt,
            "headings": heads, "lines": txt.count("\n") + 1}


def rel(path, start=ROOT):
    return os.path.relpath(path, start).replace(os.sep, "/")


def main():
    check = "--check" in sys.argv
    domains = parse_taxonomy()
    pages = defaultdict(dict)
    for p in sorted(glob.glob(os.path.join(KB, "*", "*.md"))):
        base = os.path.basename(p)
        if base.startswith("_"):
            continue
        d = os.path.basename(os.path.dirname(p))
        pages[d][base[:-3]] = parse_page(p)

    # ---------- INDEX.md ----------
    out = ["# INDEX — master topic tree", "",
           "Auto-generated by `tools/build_index.py` from `tools/taxonomy.md` and page front-matter.",
           "Edit `tools/taxonomy.md` to plan pages; do not hand-edit this file.", "",
           "Legend: ✅ written · ⬜ planned. Level / confidence come from each page's front-matter.", ""]
    total_pages = total_lines = total_q = 0
    for d in domains:
        dp = pages.get(d["id"], {})
        idx = os.path.join(KB, d["id"], "_index.md")
        head = f"## [{d['id']}](kb/{d['id']}/_index.md)" if os.path.exists(idx) else f"## {d['id']}"
        out += [f"{head} — {d['desc']}", "", "| | Page | Level | Confidence | Lines |", "|---|---|---|---|---|"]
        seen = set()
        for s in d["slugs"] + sorted(set(dp) - set(d["slugs"])):
            if s in seen:
                continue
            seen.add(s)
            if s in dp:
                pg = dp[s]
                total_pages += 1; total_lines += pg["lines"]; total_q += len(pg["questions"])
                out.append(f"| ✅ | [{pg['title']}]({rel(pg['path'])}) | {pg['fm'].get('level','')} | "
                           f"{pg['fm'].get('confidence','')} | {pg['lines']} |")
            else:
                out.append(f"| ⬜ | {s} | | | |")
        out.append("")
    out.insert(6, f"**{total_pages} pages · {total_lines} lines · {total_q} indexed questions.**\n")
    open(os.path.join(ROOT, "INDEX.md"), "w").write("\n".join(out))

    # ---------- FAQ.md ----------
    faq = ["# FAQ — every question the knowledge base answers", "",
           "Auto-generated from each page's \"Questions this page answers\" section by "
           "`tools/build_index.py`. Grouped by domain → page.", ""]
    for d in domains:
        dp = pages.get(d["id"], {})
        if not dp:
            continue
        faq += [f"## {d['id']} — {d['desc']}", ""]
        for s, pg in sorted(dp.items(), key=lambda kv: (d["slugs"].index(kv[0]) if kv[0] in d["slugs"] else 999, kv[0])):
            if not pg["questions"]:
                continue
            faq.append(f"### [{pg['title']}]({rel(pg['path'])})")
            faq += [f"- {q}" for q in pg["questions"]]
            faq.append("")
    open(os.path.join(ROOT, "FAQ.md"), "w").write("\n".join(faq))
    print(f"INDEX.md + FAQ.md rebuilt: {total_pages} pages, {total_lines} lines, {total_q} questions")

    if check:
        broken, missing = [], []
        for d, dp in pages.items():
            for s, pg in dp.items():
                for link in re.findall(r"\]\(([^)#\s]+\.md)(?:#[^)]*)?\)", pg["text"]):
                    if link.startswith("http"):
                        continue
                    tgt = os.path.normpath(os.path.join(os.path.dirname(pg["path"]), link))
                    if not os.path.exists(tgt):
                        broken.append((rel(pg["path"]), link))
                lacking = [r for r in REQUIRED if not any(h.startswith(r) for h in pg["headings"])]
                if lacking:
                    missing.append((rel(pg["path"]), lacking))
        print(f"\nBroken relative links: {len(broken)}")
        for a, b in broken:
            print(f"  {a} -> {b}")
        ctrl = [(rel(pg["path"])) for dp in pages.values() for pg in dp.values()
                if re.search(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", pg["text"])]
        print(f"\nPages with control characters (usually a LaTeX '\\a'/'\\b'/'\\f' written from a non-raw Python string): {len(ctrl)}")
        for a in ctrl:
            print(f"  {a}")
        print(f"\nPages missing template sections: {len(missing)}")
        for a, b in missing:
            print(f"  {a}: {', '.join(b)}")


if __name__ == "__main__":
    main()
