def gaseous(f, p_tot=1013.25, T=288.15, rho=7.5):
    """Specific attenuation (dB/km) of dry air (gamma_o) and water vapour (gamma_w), P.676-11 Annex 1.
    f GHz, p_tot hPa (total pressure), T K, rho water-vapour density g/m^3."""
    e = rho*T/216.7
    p = p_tot - e
    th = 300.0/T
    No = 0.0; Nw = 0.0
    for f0, a1, a2, a3, a4, a5, a6 in OXYGEN:
        S = a1*1e-7*p*th**3*np.exp(a2*(1 - th))
        df = a3*1e-4*(p*th**(0.8 - a4) + 1.1*e*th)
        df = np.sqrt(df**2 + 2.25e-6)
        dl = (a5 + a6*th)*1e-4*(p + e)*th**0.8
        F = f/f0*((df - dl*(f0 - f))/((f0 - f)**2 + df**2) + (df - dl*(f0 + f))/((f0 + f)**2 + df**2))
        No += S*F
    d = 5.6e-4*(p + e)*th**0.8
    ND = f*p*th**2*(6.14e-5/(d*(1 + (f/d)**2)) + 1.4e-12*p*th**1.5/(1 + 1.9e-5*f**1.5))
    No += ND
    for f0, b1, b2, b3, b4, b5, b6 in WATER:
        S = b1*1e-1*e*th**3.5*np.exp(b2*(1 - th))
        df = b3*1e-4*(p*th**b4 + b5*e*th**b6)
        df = 0.535*df + np.sqrt(0.217*df**2 + 2.1316e-12*f0**2/th)
        F = f/f0*(df/((f0 - f)**2 + df**2) + df/((f0 + f)**2 + df**2))
        Nw += S*F
    return 0.1820*f*No, 0.1820*f*Nw

