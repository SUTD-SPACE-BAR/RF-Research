#!/usr/bin/env python3
"""Verification for kb/10-comms-modulation/spread-spectrum-dsss-fhss-css.md

Run:  python3 tools/verify/comms_spread_spectrum.py      (~15 s)

Checks:
  1. m-sequence (degree 10, x^10 + x^3 + 1): period 1023, balance 512 ones, two-valued periodic
     autocorrelation {1023, -1}.
  2. GPS L1 C/A Gold codes: G1 = 1 + x^3 + x^10, G2 = 1 + x^2 + x^3 + x^6 + x^8 + x^9 + x^10.
     PRN 1 (phase taps 2 and 6) first 10 chips = 1440 octal (IS-GPS-200); SBAS PRNs generated by
     G2 *delay* match the gps.gov Jan-2026 PRN table (PRN 120: delay 145 -> 0671; PRN 131:
     delay 1012 -> 1226; PRN 138: delay 386 -> 1327). Cross-correlation of Gold codes takes only
     the three values {-65, -1, 63} (t(10) = 65).
  3. DSSS processing gain: BER of BPSK spread by N = 63 chips/bit against (a) a broadband Gaussian
     jammer and (b) a CW tone jammer, both at J/S = +10 dB, matches Q(sqrt(2 Eb/J0)) with
     Eb/J0 = Gp * S/J (tone case: Gaussian approximation).
  4. Chirp spread spectrum (LoRa-style): dechirp + FFT recovers the symbol; a carrier offset of
     one bin (BW / 2^SF) shifts the decision by exactly one symbol; bin widths at SF7/SF12.
  5. Link numbers: GPS C/A PSD below kT, processing gain, C/N0 and Eb/N0 at -128.5 dBm.
"""
import numpy as np
from scipy import special

rng = np.random.default_rng(4)
ok_all = True


def check(name, got, want, tol, rel=False):
    global ok_all
    err = abs(got - want) / (abs(want) if rel else 1.0)
    ok = err <= tol
    ok_all &= ok
    print(f"[{'PASS' if ok else 'FAIL'}] {name}: got {got:.6g}, expected {want:.6g} (tol {tol}{' rel' if rel else ''})")


def lfsr(taps, n, length, init=None):
    """Fibonacci LFSR; taps = exponents of the feedback polynomial (excluding 0), degree n.
    Output = last stage. Register index 1..n."""
    reg = [1] * n if init is None else list(init)
    out = []
    for _ in range(length):
        out.append(reg[-1])
        fb = 0
        for tp in taps:
            fb ^= reg[tp - 1]
        reg = [fb] + reg[:-1]
    return np.array(out)

# ------------------------------------------------------------------------------ 1
m = lfsr([3, 10], 10, 2046)
per = m[:1023]
check("m-sequence period repeats", float(np.array_equal(m[:1023], m[1023:])), 1.0, 0)
check("m-sequence balance (# ones)", per.sum(), 512, 0)
b = 1 - 2 * per
ac = np.array([np.dot(b, np.roll(b, k)) for k in range(1023)])
check("m-seq autocorr peak", ac[0], 1023, 0)
check("m-seq autocorr off-peak max |R|", np.max(np.abs(ac[1:] + 1)), 0, 0)

# ------------------------------------------------------------------------------ 2


def gps_g1g2(length=1023):
    g1 = [1] * 10
    g2 = [1] * 10
    G1, G2 = [], []
    for _ in range(length):
        G1.append(g1[9])
        G2.append(g2[9])
        f1 = g1[2] ^ g1[9]
        f2 = g2[1] ^ g2[2] ^ g2[5] ^ g2[7] ^ g2[8] ^ g2[9]
        g1 = [f1] + g1[:9]
        g2 = [f2] + g2[:9]
    return np.array(G1), np.array(G2), None


def ca_by_taps(t1, t2):
    g1 = [1] * 10
    g2 = [1] * 10
    out = []
    for _ in range(1023):
        out.append(g1[9] ^ g2[t1 - 1] ^ g2[t2 - 1])
        f1 = g1[2] ^ g1[9]
        f2 = g2[1] ^ g2[2] ^ g2[5] ^ g2[7] ^ g2[8] ^ g2[9]
        g1 = [f1] + g1[:9]
        g2 = [f2] + g2[:9]
    return np.array(out)


def ca_by_delay(delay):
    G1, G2, _ = gps_g1g2()
    return G1 ^ np.roll(G2, delay)


def first10_octal(code):
    v = int("".join(str(int(c)) for c in code[:10]), 2)
    return int(oct(v)[2:])


check("GPS PRN 1 (taps 2,6) first 10 chips [octal]", first10_octal(ca_by_taps(2, 6)), 1440, 0)
check("GPS PRN 2 (taps 3,7) first 10 chips [octal]", first10_octal(ca_by_taps(3, 7)), 1620, 0)
check("PRN1 taps (2,6) == G2 delay 5 chips", float(np.array_equal(ca_by_taps(2, 6), ca_by_delay(5))), 1.0, 0)
for prn, delay, want in ((120, 145, 671), (131, 1012, 1226), (138, 386, 1327), (133, 603, 46)):
    check(f"SBAS PRN {prn} (G2 delay {delay}) first 10 chips [octal] vs gps.gov table", first10_octal(ca_by_delay(delay)), want, 0)
codes = [1 - 2 * ca_by_delay(d) for d in (5, 6, 7, 8, 17, 18, 139, 140)]
vals = set()
for i in range(len(codes)):
    for j in range(i + 1, len(codes)):
        cc = np.real(np.fft.ifft(np.fft.fft(codes[i]) * np.conj(np.fft.fft(codes[j]))))
        vals |= set(np.round(cc).astype(int))
print("  Gold cross-correlation values found:", sorted(vals))
check("Gold cross-correlation is three-valued {-65,-1,63}", float(vals <= {-65, -1, 63}), 1.0, 0)
auto = np.real(np.fft.ifft(np.abs(np.fft.fft(codes[0])) ** 2))
check("C/A autocorrelation max sidelobe |R| = 65", np.max(np.abs(np.round(auto[1:]))), 65, 0)

# ------------------------------------------------------------------------------ 3
N = 63
nbits = 100000
SJ_db = -13.0                # S/J = -13 dB (jammer 13 dB stronger than the signal)
S = 1.0
J = S / 10 ** (SJ_db / 10)
bits = 1 - 2 * rng.integers(0, 2, nbits)
code = 1 - 2 * rng.integers(0, 2, (nbits, N))          # long pseudo-random code (chip-level)
tx = (bits[:, None] * code) * np.sqrt(S)                # chips at unit symbol rate; S per chip
Gp = N
EbJ0 = Gp * S / J
pb_th = 0.5 * special.erfc(np.sqrt(EbJ0))
# Passband model mapped to the in-phase (real) baseband rail after coherent demodulation:
# signal power S -> amplitude sqrt(S) per chip; a passband jammer of power J spread over the chip
# bandwidth W = Rc -> in-phase noise variance J/2 per chip (J0 = J/Rc one-sided); a passband CW
# jammer of power J -> in-phase sinusoid of amplitude sqrt(J) (power J/2).
# (a) broadband Gaussian jammer
jam = np.sqrt(J / 2) * rng.standard_normal((nbits, N))
z = np.sum((tx + jam) * code, axis=1)
pb_a = np.mean(np.sign(z) != bits)
print(f"  DSSS N={N} (Gp {10*np.log10(N):.1f} dB), J/S = {-SJ_db:.0f} dB -> Eb/J0 = {10*np.log10(EbJ0):.2f} dB, theory BER {pb_th:.3e}")
check("DSSS vs broadband jammer BER = Q(sqrt(2 Eb/J0))", pb_a, pb_th, 0.15, rel=True)
# (b) CW tone jammer at random frequency inside the band, power J (real sinusoid)
k = np.arange(nbits * N).reshape(nbits, N)
f = 0.137
jam = np.sqrt(J) * np.cos(2 * np.pi * f * k + 0.3)
z = np.sum((tx + jam) * code, axis=1)
pb_b = np.mean(np.sign(z) != bits)
check("DSSS vs CW jammer BER ~ Gaussian approx (spread jammer)", pb_b, pb_th, 0.25, rel=True)
# no spreading: same jammer directly on BPSK (S/J = -10 dB) -> hopeless
z0 = bits * np.sqrt(S) + np.sqrt(J / 2) * rng.standard_normal(nbits)
print(f"  same jammer without spreading: BER {np.mean(np.sign(z0) != bits):.3f}")
jm = 10 * np.log10(Gp) - 9.59 - 2.0
print(f"  jamming margin for BER 1e-5 with 2 dB losses: {jm:.1f} dB")

# ------------------------------------------------------------------------------ 4
BW = 125e3
for SF in (7, 12):
    M = 2 ** SF
    n = np.arange(M)
    fs = BW
    base = np.exp(1j * np.pi * n ** 2 / M)          # up-chirp sweeping BW at 1 sample/chip
    sym = 37
    tx = np.exp(1j * np.pi * ((n + sym) % M) ** 2 / M) * np.exp(-1j * np.pi * 0)   # cyclic shift
    # proper LoRa cyclic-shift chirp: frequency starts at sym*BW/M and wraps
    tx = np.exp(1j * 2 * np.pi * (n ** 2 / (2 * M) + (sym / M - 0.5) * n))
    dech = tx * np.conj(np.exp(1j * 2 * np.pi * (n ** 2 / (2 * M) - 0.5 * n)))
    dem = np.argmax(np.abs(np.fft.fft(dech)))
    check(f"CSS SF{SF}: dechirp+FFT recovers symbol", dem, sym, 0)
    bin_hz = BW / M
    cfo = np.exp(1j * 2 * np.pi * bin_hz * n / fs)
    dem2 = np.argmax(np.abs(np.fft.fft(dech * cfo)))
    check(f"CSS SF{SF}: CFO of one bin ({bin_hz:.1f} Hz) shifts symbol by 1", dem2 - dem, 1, 0)
    print(f"  SF{SF}/125 kHz: bin = {bin_hz:.2f} Hz; 1.44 kHz Doppler (1000 m/s @ 433 MHz) = {1444.3/bin_hz:.1f} bins; symbol time {M/BW*1e3:.3f} ms")

# ------------------------------------------------------------------------------ 5
P = -128.5          # dBm, IS-GPS-200 minimum L1 C/A (-158.5 dBW)
psd = P - 10 * np.log10(2.046e6)
check("GPS C/A PSD (main lobe 2.046 MHz) [dBm/Hz]", psd, -191.6, 0.1)
check("GPS C/A C/N0 with 2 dB NF [dB-Hz]", P - (-174 + 2), 43.5, 0.1)
check("GPS C/A processing gain chips per data bit [dB]", 10 * np.log10(1.023e6 / 50), 43.1, 0.05)

print("\nOVERALL:", "PASS" if ok_all else "FAIL")
